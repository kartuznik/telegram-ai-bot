def _is_thanks_or_ack(t: str) -> bool:
    if t in _THANKS_OR_ACK:
        return True
    if t.startswith(("спасибо", "благодарю", "ок ", "ок,")):
        return True
    return False


def _last_role(history: list[dict[str, str]]) -> str | None:
    if not history:
        return None
    return history[-1].get("role")


def _looks_like_follow_up_to_assistant(user_text: str) -> bool:
    """Короткая реплика после ответа бота — не новая «размытая тема»."""
    t = normalize_user_text(user_text)
    if not t:
        return False
    if len(t) > 160:
        return True
    if len(t) < 55 and "еще" in t:
        return True
    for hint in _FOLLOWUP_HINTS:
        if hint in t:
            return True
    return False


def should_offer_clarification_turn(
    user_text: str,
    *,
    web_search_enriched: bool,
    history_tail: list[dict[str, str]],
) -> bool:
    """
    True — в этом ходе можно включить режим «одно уточнение вместо лекции».
    Не заменяет решение модели; лишь разрешает подмешать оверлей к system.
    """
    if web_search_enriched:
        return False
    raw = (user_text or "").strip()
    t = normalize_user_text(raw)
    if not t:
        return False
    if "[изображение]" in t or "пользователь прислал файл" in t:
        return False
    if _is_thanks_or_ack(t):
        return False
    if _looks_like_follow_up_to_assistant(raw) and _last_role(history_tail) == "assistant":
        return False
    for block in _FACTUAL_SUBSTRINGS:
        if block in t:
            return False
    for sig in _VAGUE_SUBSTRINGS:
        if sig in t:
            return True
    return False


